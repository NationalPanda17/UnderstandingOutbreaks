// After `vite build`: write Cloudflare Pages routing and headers, split out R2-hosted files, and enforce Pages limits.
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
const root = new URL('..', import.meta.url).pathname;
const dist = join(root, 'dist');
const site = JSON.parse(readFileSync(join(root, '..', 'config', 'site.json'), 'utf8'));
const locales = site.locales.map((l) => l.code);

// ---- routing: every locale path serves the app shell; /embed/* serves the embed shell
const redirects = [`/ /${site.defaultLocale}/ 302`, ...locales.map((l) => `/${l}/* /index.html 200`), '/embed/* /embed 200']; // no .html: Cloudflare Pages redirects .html targets to the pretty URL and drops the path;
writeFileSync(join(dist, '_redirects'), redirects.join('\n') + '\n');

// ---- headers. Rules never overlap, so the embed routes can allow framing while everything else forbids it.
const r2 = /^https?:\/\//.test(site.r2BaseUrl) ? new URL(site.r2BaseUrl).origin : '';
const tools = /^https?:\/\//.test(site.toolAssetsBaseUrl) ? new URL(site.toolAssetsBaseUrl).origin : '';
const basemap = /^https?:\/\//.test(site.basemapUrl) ? new URL(site.basemapUrl).origin : '';
const ext = [...new Set([r2, tools, basemap].filter(Boolean))].join(' ');
const csp = (ancestors) => [
  `default-src 'self'`, `script-src 'self' 'wasm-unsafe-eval' blob:${tools ? ' ' + tools : ''}`, `worker-src 'self' blob:`, `style-src 'self' 'unsafe-inline'`,
  `img-src 'self' data: blob:`, `font-src 'self' data:`, `connect-src 'self' blob: data:${ext ? ' ' + ext : ''}`, `frame-src 'self'${tools ? ' ' + tools : ''}`,
  `object-src 'none'`, `base-uri 'self'`, `form-action 'none'`, `frame-ancestors ${ancestors}`,
].join('; ');
const common = ['  X-Content-Type-Options: nosniff', '  Referrer-Policy: no-referrer', '  Permissions-Policy: geolocation=(), camera=(), microphone=(), interest-cohort=()'];
const block = (path, ancestors) => [path, `  Content-Security-Policy: ${csp(ancestors)}`, ...common, ''];
const headers = [
  '# Generated by scripts/postbuild.mjs. No cookies are set anywhere. Only /embed routes may be framed by other sites.',
  ...block('/', `'none'`), ...block('/index.html', `'none'`), ...locales.flatMap((l) => block(`/${l}/*`, `'none'`)),
  ...block('/embed/*', '*'), ...block('/embed', '*'), ...block('/embed.html', '*'),
  '/assets/*', '  Cache-Control: public, max-age=31536000, immutable', '',
  '/data/*', '  Access-Control-Allow-Origin: *', '  Cache-Control: public, max-age=300', '',
  '/data/v1/snapshots/*', '  Access-Control-Allow-Origin: *', '  Cache-Control: public, max-age=31536000, immutable', '',
  '/notebooks/*', '  Access-Control-Allow-Origin: *', '',
];
writeFileSync(join(dist, '_headers'), headers.join('\n'));

// ---- R2: files under /r2 are uploaded to the bucket, not to Pages (unless UO_KEEP_R2=1 for a local preview)
const r2dir = join(dist, 'r2'); const r2out = join(root, 'dist-r2');
// webR is the exception: every file is under the Pages size limit, and loading it from another origin fails (its
// worker reads lazily loaded files with cross-origin XHR). So it is served by Pages itself, at /tools/webr/.
{
  const webr = join(r2dir, 'tools', 'webr');
  if (existsSync(webr)) { mkdirSync(join(dist, 'tools'), { recursive: true }); rmSync(join(dist, 'tools', 'webr'), { recursive: true, force: true }); renameSync(webr, join(dist, 'tools', 'webr')); }
}
if (existsSync(r2dir)) {
  rmSync(r2out, { recursive: true, force: true });
  if (process.env.UO_KEEP_R2 === '1') cpSync(r2dir, r2out, { recursive: true }); else renameSync(r2dir, r2out);
}

// ---- Cloudflare Pages limits: 25 MiB per file, 20,000 files
let count = 0; let total = 0; const big = [];
const walk = (d) => { for (const f of readdirSync(d)) { const p = join(d, f); const st = statSync(p); if (st.isDirectory()) { if (process.env.UO_KEEP_R2 === '1' && p === r2dir) continue; walk(p); } else { count++; total += st.size; if (st.size > 25 * 1024 * 1024) big.push(`${p.slice(dist.length)} (${(st.size / 1048576).toFixed(1)} MB)`); } } };
walk(dist);
console.log(`[postbuild] ${count} files, ${(total / 1048576).toFixed(1)} MB for Pages; R2 files in dist-r2/`);
if (big.length) { console.error('[postbuild] files over the 25 MB Pages limit (move them to R2):\n  ' + big.join('\n  ')); process.exit(1); }
if (count > 20000) { console.error(`[postbuild] ${count} files exceeds the Pages limit of 20,000`); process.exit(1); }

// ---- production must never ship test fixtures
const manifestPath = join(dist, 'data', 'v1', 'sources.json');
if (existsSync(manifestPath) && /"test_data"|TEST DATA/.test(readFileSync(manifestPath, 'utf8'))) { console.error('[postbuild] TEST DATA source found in published data'); process.exit(1); }
