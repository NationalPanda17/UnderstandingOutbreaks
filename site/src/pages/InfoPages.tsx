/** Render translated paragraphs base.p1, base.p2, ... and optional bullet list base.li1, ... */
export function Paras({ base }: { base: string }) {
  const ps: string[] = []; const lis: string[] = [];
  for (let i = 1; hasKey(`${base}.p${i}`); i++) ps.push(t(`${base}.p${i}`));
  for (let i = 1; hasKey(`${base}.li${i}`); i++) lis.push(t(`${base}.li${i}`));
  return <>{ps.map((p, i) => <p key={i}>{p}</p>)}{lis.length > 0 && <ul>{lis.map((l, i) => <li key={i}>{l}</li>)}</ul>}</>;
}
export function Sections({ base, ids }: { base: string; ids: string[] }) {
  return <>{ids.map((id) => <section key={id} id={id}><h2>{t(`${base}.${id}.title`)}</h2><Paras base={`${base}.${id}`} /></section>)}</>;
}
/** schema.org/Dataset JSON-LD for dataset pages (generated by the pipeline, injected into the document head). */
function useDatasetJsonLd() {
  useEffect(() => {
    let el: HTMLScriptElement | null = null;
    getOptional<any>('catalog/dataset.jsonld').then((doc) => { if (!doc) return; el = document.createElement('script'); el.type = 'application/ld+json'; el.dataset.uo = 'dataset'; el.textContent = JSON.stringify(doc); document.head.appendChild(el); });
    return () => { el?.remove(); };
  }, []);
}
